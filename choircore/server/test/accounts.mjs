import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createAccounts} from '../accounts.mjs';
const temp=mkdtempSync(join(tmpdir(),'choir-accounts-'));
const file=join(temp,'accounts.sqlite');
let db=createAccounts(file);
try{
 const registered=await db.register({email:'owner@example.test',password:'disposable-account-test-password',workspaceName:'Test Choir'});
 assert.equal(registered.active,false);
 assert.equal(db.approve(registered.workspaceId),true);
 const now=Date.now();
 const room='CL-SESSION-persistence-fixture';
 const initial={workspaceId:registered.workspaceId,title:'Durable Choir rehearsal',createdAt:now,startsAt:now+60000,expiresAt:now+120000,manager:Buffer.alloc(32,1),roles:{singer:Buffer.alloc(32,2),conductor:Buffer.alloc(32,3),engineer:Buffer.alloc(32,4)}};
 db.saveRehearsal(room,initial);
 const rotated={...initial.roles,singer:Buffer.alloc(32,5)};db.rotateRehearsal(room,rotated);
 db.close();db=createAccounts(file);
 const restored=db.restoreRehearsals(now);assert.equal(restored.length,1);assert.equal(restored[0][0],room);assert.deepEqual(restored[0][1].roles.singer,rotated.singer);
 assert.equal(restored[0][1].startsAt,initial.startsAt);
 db.closeRehearsal(room,'cancelled',now+1000);assert.equal(db.restoreRehearsals(now+2000).length,0);
 assert.equal(db.rehearsalHistory(registered.workspaceId)[0].status,'cancelled');
 assert.equal(db.rehearsalHistory('unrelated-workspace').length,0);
 db.saveRehearsal('expiry-fixture',{...initial,startsAt:now,expiresAt:now+5000});
 assert.equal(db.restoreRehearsals(now+6000).length,0);assert.equal(db.rehearsalHistory(registered.workspaceId)[0].status,'expired');
 const loggedIn=await db.login({email:'OWNER@example.test',password:'disposable-account-test-password'});
 assert.ok(loggedIn?.active);
 assert.equal(loggedIn.workspaceId,registered.workspaceId);
 assert.equal(db.authenticate(loggedIn.authToken)?.workspaceId,registered.workspaceId);
 db.logout(loggedIn.authToken);assert.equal(db.authenticate(loggedIn.authToken),null);
 console.log('Account persistence and lifecycle passed');
}finally{db.close();rmSync(temp,{recursive:true,force:true});}
